"""Composite Final score from the three layers for the n=100 main run.

Merges, per layer, the main n=100 scores (B1-B6, B8) with the B7-v2 scores
(faithful CoVe, regenerated after the _tool_analyze fix), then computes:
    Final = 0.35*(L1*100) + 0.30*(L2*100) + 0.35*(L3*20)        in [0,100]
with L1, L2 in [0,1] and L3 in [0,5]. Reports mean +/- std over instances
(dispersion proxy; 5-seed variance to be added for the final table).

Outputs runs/n100_final_summary.csv and a LaTeX table snippet at
analysis/n100_main_table.tex (drop-in for section5_draft.tex Table 2).
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

import config as C

MAIN = "reports_main_glm_n100"
B7V2 = "reports_main_glm_n100_B7_v2"
B1B2B8V3 = "reports_main_glm_n100_B1B2B8_v3"   # rule-engine M (no oracle labels)
# which systems come from which source (after the rule-engine / CoVe fixes)
SRC = {s: MAIN for s in ["B3", "B4", "B5", "B6"]}
SRC["B7"] = B7V2
for s in ["B1", "B2", "B8"]:
    SRC[s] = B1B2B8V3
LAYERS = [("L1", "L1"), ("L2", "L2"), ("L3", "L3")]
ORDER = ["B1", "B2", "B3", "B4", "B5", "B6", "B7", "B8"]
NAMES = {"B1": "Template-only (no LLM)", "B2": "Traditional D2T", "B3": "Direct LLM",
         "B4": "Few-shot LLM", "B5": "Tool-using agent", "B6": "RAG",
         "B7": "RAG + CoVe", "B8": "Proposed framework"}
W = {"L1": 0.35, "L2": 0.30, "L3": 0.35}


def _layer_df(col):
    """Assemble one layer's per-instance scores from the honest sources:
    B3-B6 from main, B7 from B7_v2, B1/B2/B8 from the rule-engine v3 run."""
    frames = []
    for sysname in ORDER:
        src = SRC[sysname]
        path = C.RUNS_DIR / f"{src}_{col.lower()}.parquet"
        if not path.exists():
            print(f"WARN: {path.name} missing -> {sysname} absent for {col}")
            continue
        d = pd.read_parquet(path)
        d = d[d["method"] == sysname][["method", "instance_id", col]]
        frames.append(d)
    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


def main():
    # build per-instance L1/L2/L3 by merging the three honest sources
    inst = None
    for key, col in LAYERS:
        d = _layer_df(col).rename(columns={col: key})
        if d.empty:
            print(f"SKIP {key}: no source data"); continue
        inst = d if inst is None else inst.merge(d, on=["method", "instance_id"], how="outer")
    if inst is None:
        print("No data; score the layers first."); return
    inst["Final"] = (0.35 * inst["L1"] * 100 + 0.30 * inst["L2"] * 100
                     + 0.35 * inst["L3"] * 20).round(2)

    g = inst.groupby("method")
    summ = pd.DataFrame({
        "L1_mean": g["L1"].mean(), "L1_sd": g["L1"].std(),
        "L2_mean": g["L2"].mean(), "L2_sd": g["L2"].std(),
        "L3_mean": g["L3"].mean(), "L3_sd": g["L3"].std(),
        "Final_mean": g["Final"].mean(), "Final_sd": g["Final"].std(),
        "n": g["Final"].size(),
    }).round(3).reindex([m for m in ORDER if m in g.groups])

    summ.insert(0, "system", [NAMES[m] for m in summ.index])
    summ.to_csv(C.RUNS_DIR / "n100_final_summary.csv")

    print(summ.to_string())

    # LaTeX drop-in for section5_draft.tex main table
    L = ["% Auto-generated by composite_final.py (n=100, primary LLM, cross-judge L2/L3)\n"]
    L.append("\\begin{tabular}{lcrrrr}\n\\toprule\n")
    L.append("ID & System & L1 & L2 & L3 & Final \\\\\n\\midrule\n")
    for m in summ.index:
        r = summ.loc[m]
        bold = "\\textbf{" if m == "B8" else ""
        bend = "}" if m == "B8" else ""
        L.append(f"{bold}{m}{bend} & {NAMES[m]} & "
                 f"{r['L1_mean']:.2f} & {r['L2_mean']:.2f} & {r['L3_mean']:.2f} & "
                 f"{r['Final_mean']:.1f}$\\pm${r['Final_sd']:.1f} \\\\\n")
    L.append("\\bottomrule\n\\end{tabular}\n")
    (C.ANALYSIS_DIR / "n100_main_table.tex").write_text("".join(L), encoding="utf-8")
    print("\nWrote runs/n100_final_summary.csv and analysis/n100_main_table.tex")


if __name__ == "__main__":
    main()
