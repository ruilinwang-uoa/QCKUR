"""Compare GLM-5.3-judged vs DeepSeek-judged cross-LLM results (B1-B8, n=100).

All reports were generated by DeepSeek-V4-Flash. Final = 0.35*L1*100 +
0.30*L2*100 + 0.35*L3*20 (L1 judge-independent). Outputs per-system Finals,
Spearman rank agreement between judges, and paired Wilcoxon B8 vs B3-B7.
"""
from __future__ import annotations

import pandas as pd
from scipy import stats

import config as C

ORDER = ["B1", "B2", "B3", "B4", "B5", "B6", "B7", "B8"]
W = {"L1": 0.35, "L2": 0.30, "L3": 0.35}

l1 = pd.read_parquet(C.RUNS_DIR / "reports_crossllm_deepseek_n100_l1.parquet")
l1 = l1[l1["method"].isin(ORDER)][["method", "instance_id", "L1"]]

def load(tag_l2: str, tag_l3: str) -> pd.DataFrame:
    l2 = pd.read_parquet(C.RUNS_DIR / tag_l2)[["method", "instance_id", "L2"]]
    l3 = pd.read_parquet(C.RUNS_DIR / tag_l3)[["method", "instance_id", "L3", "coverage", "ok"]]
    d = l1.merge(l2, on=["method", "instance_id"]).merge(l3, on=["method", "instance_id"])
    d["Final"] = W["L1"] * d["L1"] * 100 + W["L2"] * d["L2"] * 100 + W["L3"] * d["L3"] * 20
    return d

glm = load("reports_crossllm_deepseek_n100_B1B8_glm53_l2.parquet",
           "reports_crossllm_deepseek_n100_B1B8_glm53_l3.parquet")
ds = load("reports_crossllm_deepseek_n100_B1B8_l2.parquet",
          "reports_crossllm_deepseek_n100_B1B8_l3.parquet")

print("rows: glm =", len(glm), "| deepseek =", len(ds))
print("judge call failures (ok=False): glm =", int((~glm["ok"]).sum()),
      "| deepseek =", int((~ds["ok"]).sum()))

gm = glm.groupby("method")["Final"].agg(["mean", "std"]).reindex(ORDER)
dm = ds.groupby("method")["Final"].agg(["mean", "std"]).reindex(ORDER)
cov_glm = glm.groupby("method")["coverage"].apply(
    lambda s: s.apply(lambda c: sum(c.values())).mean()).reindex(ORDER)
cov_ds = ds.groupby("method")["coverage"].apply(
    lambda s: s.apply(lambda c: sum(c.values())).mean()).reindex(ORDER)

tbl = pd.DataFrame({"DS_Final": dm["mean"].round(1), "GLM53_Final": gm["mean"].round(1),
                    "GLM53_std": gm["std"].round(1), "Delta": (gm["mean"] - dm["mean"]).round(1),
                    "DS_Cov": cov_ds.round(2), "GLM53_Cov": cov_glm.round(2)})
print("\n=== per-system Final (both judge DeepSeek-generated reports) ===")
print(tbl.to_string())

rho, p_rho = stats.spearmanr(dm["mean"].values, gm["mean"].values)
print(f"\nSpearman rho = {rho:.4f} (p = {p_rho:.2e})")

print("\n=== paired Wilcoxon, B8 vs B3-B7, GLM-5.3 judge (per-instance Final) ===")
wide = glm.pivot_table(index="instance_id", columns="method", values="Final")
for b in ["B3", "B4", "B5", "B6", "B7"]:
    d = wide["B8"] - wide[b]
    w = stats.wilcoxon(d, zero_method="wilcox", method="auto")
    z = (d > 0).mean()
    print(f"B8 vs {b}: median diff = {d.median():+.1f}, mean diff = {d.mean():+.1f}, "
          f"win rate = {z:.0%}, W = {w.statistic:.0f}, p = {w.pvalue:.2e}")

# same paired tests under the DeepSeek judge, for reference
print("\n=== paired Wilcoxon, B8 vs B3-B7, DeepSeek judge (reference) ===")
wide_ds = ds.pivot_table(index="instance_id", columns="method", values="Final")
for b in ["B3", "B4", "B5", "B6", "B7"]:
    d = wide_ds["B8"] - wide_ds[b]
    w = stats.wilcoxon(d, zero_method="wilcox", method="auto")
    print(f"B8 vs {b}: mean diff = {d.mean():+.1f}, p = {w.pvalue:.2e}")

# Layer-level detail for the paper text
print("\n=== GLM-5.3 judge layer means (B2 vs B8 detail) ===")
for m in ["B1", "B2", "B8"]:
    sub = glm[glm["method"] == m]
    l2sub = pd.read_parquet(C.RUNS_DIR / "reports_crossllm_deepseek_n100_B1B8_glm53_l2.parquet")
    l2m = l2sub[l2sub["method"] == m]
    print(f"{m}: L1={sub['L1'].mean():.3f} L2={sub['L2'].mean():.3f} "
          f"(cons={l2m['consistency'].mean():.3f} contra={l2m['contradiction'].mean():.3f}) "
          f"L3={sub['L3'].mean():.2f} Final={sub['Final'].mean():.1f}")

out = tbl.copy()
out.insert(0, "System", ORDER)
out.to_csv(C.ANALYSIS_DIR / "glm53_crossjudge_comparison.csv", index=False)
print("\nsaved:", C.ANALYSIS_DIR / "glm53_crossjudge_comparison.csv")
