"""End-to-end paraphrase robustness run (closes the checklist item:
"no end-to-end run measuring answer quality under paraphrased input").

Design (faithful to the architecture of Section 3): the report pipeline is
question-mediated upstream -- the matcher routes each user question to a bank
unit (exact-text rule: the matcher must return a bank question verbatim, or
NO MATCH), the routed units' handlers fill the backbone, and the refinement
LLM verbalizes it. The canonical campaign feeds verbatim bank questions
(p_m = 1.00). This run feeds PARAPHRASES:

  * condition "bank": the bank's own paraphrase (paraphrases[0]) of each of
    the six canonical per-aspect questions;
  * condition "adv":  adversarially reworded paraphrases of the same six
    questions, generated by the primary LLM with instructions to change
    wording substantially while keeping the meaning.

Stages (each resume-safe, state in runs/paraphrase_state.json):
  1. adversarial paraphrase generation (6 primary-LLM calls);
  2. matcher routing for 6 questions x {bank[0], bank[1], adv} (18 calls,
     primary LLM, the Section 3.6 matching prompt, seed 42, exact-text rule);
  3. report generation for the 100 canonical instances x 2 conditions
     (100 + 100 calls): the backbone is composed from the ROUTED units
     (mis-route -> the wrong unit's answer under the intended aspect label;
     abstention -> that aspect is missing); refinement identical to B8;
  4. writes runs/reports_paraphrase_bank_B8.parquet and
     runs/reports_paraphrase_adv_B8.parquet (method B8PB / B8PA), ready for
     layer1_reports.py / layer2_eval.py / layer3_eval.py.
"""
from __future__ import annotations

import difflib
import json
import random
import time

import pandas as pd

import config as C
import background as bg
import ku_handlers as kh
import llm_call
import llm_config
import templates as Tpl
from systems import REPORT_TASK

PROVIDER = "openai"          # primary generation model (GLM-4-Flash)
SEED = 42
N_INSTANCES = 100

MATCH_SYSTEM = """You are a semantic matching assistant for an analytics question bank.
Given a user question and the question bank, decide which single abstract
question in the bank the user question semantically matches.  Return ONLY the
exact text of that bank question, copied verbatim, or the token NO MATCH if no
bank question matches.  Output nothing else."""

ADV_SYSTEM = ("You are an expert at rewording questions. Rewrite the question with "
              "substantially different wording and sentence structure while keeping "
              "exactly the same meaning. Do not reuse the original's key phrases. "
              "Return only the rewritten question.")

STATE_PATH = C.RUNS_DIR / "paraphrase_state.json"


def norm(s: str) -> str:
    return " ".join((s or "").strip().lower().split())


def load_state() -> dict:
    if STATE_PATH.exists():
        return json.loads(STATE_PATH.read_text(encoding="utf-8"))
    return {}


def save_state(st: dict) -> None:
    STATE_PATH.write_text(json.dumps(st, indent=2, ensure_ascii=False), encoding="utf-8")


def canonical_questions() -> list[dict]:
    bank = bg._bank()
    out = []
    for category, handler, args in bg.CANONICAL_KUS:
        q = next(x for x in bank if x["handler"] == handler and x["args"] == args)
        out.append(q)
    return out


def match_one(question: str, bank_block: str) -> str:
    user = (f"MODEL CONTEXT: predictive maintenance of a milling machine "
            f"(AI4I 2020 data: temperature, rotational speed, torque, tool "
            f"wear; failure modes TWF/HDF/PWF/OSF/RNF; logistic regression "
            f"/ random forest / gradient boosting models).\n\nQUESTION BANK:\n"
            f"{bank_block}\n\nUSER QUESTION: {question}\n\n"
            f"Return the exact matching bank question text, or NO MATCH.")
    res = llm_call.chat(PROVIDER, [{"role": "system", "content": MATCH_SYSTEM},
                                   {"role": "user", "content": user}], seed=SEED)
    return res["text"].strip()


def classify(output: str, target: str, bank_norm: dict[str, dict]) -> dict:
    n = norm(output)
    if n == "no match":
        return {"verdict": "abstain", "routed_id": None}
    if n in bank_norm:
        q = bank_norm[n]
        if q["text"] == target:
            return {"verdict": "exact", "routed_id": q["id"]}
        return {"verdict": "rerouted", "routed_id": q["id"]}
    ratio = difflib.SequenceMatcher(None, n, norm(target)).ratio()
    if ratio > 0.85:
        return {"verdict": "minor-deviation (abstains under exact lookup)",
                "routed_id": None}
    return {"verdict": "unparseable (abstains)", "routed_id": None}


def run_unit(q: dict, row: dict, ctx: dict) -> dict:
    rrow = bg._rule_row(row)
    slots = kh.run_handler(q["handler"], rrow, ctx, q["args"])
    text = Tpl.render(q.get("template_id", q["handler"]), q["category"], slots)
    return {"category": q["category"], "ku_id": q["id"], "question": q["text"],
            "handler": q["handler"], "slots": slots, "answer": text}


def refine(row: dict, ctx: dict, backbone: str) -> dict:
    prompt = (bg.background_text(ctx) + "\nINSTANCE:\n" + bg.instance_context(row) +
              "\n\nVERIFIED ANALYTICAL FINDINGS (knowledge-unit answers; use ONLY these facts):\n"
              + backbone + "\n\nTASK:\n" + REPORT_TASK +
              "\nThe findings are computed by the analytical components and are authoritative; "
              "verbalize them into a fluent report without changing any value.")
    res = llm_call.chat(PROVIDER, [{"role": "system", "content": "You are a predictive-maintenance report writer."},
                                   {"role": "user", "content": prompt}], seed=SEED)
    return res


def _append_rows(out_path, new_rows) -> None:
    """Append only NEW rows to the checkpoint parquet (never re-append)."""
    import pandas as pd  # local import to keep module import light
    prev = pd.read_parquet(out_path) if out_path.exists() else pd.DataFrame()
    pd.concat([prev, pd.DataFrame(new_rows)], ignore_index=True).to_parquet(out_path, index=False)


def main() -> None:
    if not llm_config.get_provider(PROVIDER).is_configured:
        print("ERROR: primary provider not configured"); return
    st = load_state()
    bank = bg._bank()
    bank_norm = {norm(q["text"]): q for q in bank}
    bank_block = "\n".join(f"- {q['text']}" for q in bank)
    canon = canonical_questions()

    # ---- stage 1: adversarial paraphrases ----
    if "adv" not in st:
        st["adv"] = {}
        for q in canon:
            res = llm_call.chat(PROVIDER, [{"role": "system", "content": ADV_SYSTEM},
                                           {"role": "user", "content": q["text"]}], seed=SEED)
            st["adv"][q["id"]] = res["text"].strip().strip('"')
            print(f"adv paraphrase [{q['category']}]: {st['adv'][q['id']][:70]}")
        save_state(st)

    # ---- stage 2: matcher routing ----
    if "routing" not in st:
        st["routing"] = {}
        for q in canon:
            for kind, question in (("bank0", q["paraphrases"][0]),
                                   ("bank1", q["paraphrases"][1]),
                                   ("adv", st["adv"][q["id"]])):
                out = match_one(question, bank_block)
                cls = classify(out, q["text"], bank_norm)
                st["routing"][f"{q['id']}|{kind}"] = {"question": question,
                                                      "matcher_output": out, **cls}
                print(f"match [{kind}] {q['id']}: {cls['verdict']}")
        save_state(st)

    # ---- stage 3: generation ----
    sample = pd.read_parquet(C.DATA_DIR / "sample_315.parquet")
    ctx = bg.build_ctx()
    src = pd.read_parquet(C.RUNS_DIR / "reports_main_glm_n100_B1B2B8_v3.parquet")
    insts = src[src["method"] == "B8"][["instance_id", "machine_failure"]].head(N_INSTANCES)

    for cond, kind, method, fname in (("bank", "bank0", "B8PB", "reports_paraphrase_bank_B8"),
                                      ("adv", "adv", "B8PA", "reports_paraphrase_adv_B8")):
        out_path = C.RUNS_DIR / f"{fname}.parquet"
        done = set()
        if out_path.exists():
            prev = pd.read_parquet(out_path)
            done = set(zip(prev["method"], prev["instance_id"]))
        routed = {}   # canonical id -> bank question dict or None
        for q in canon:
            r = st["routing"][f"{q['id']}|{kind}"]
            routed[q["id"]] = next((b for b in bank if b["id"] == r["routed_id"]), None) \
                if r["routed_id"] else None
        n_missing = sum(1 for q in canon if routed[q["id"]] is None)
        n_wrong = sum(1 for q in canon if routed[q["id"]] and routed[q["id"]]["id"] != q["id"])
        print(f"\ncondition {cond}: routed correctly {6 - n_missing - n_wrong}/6, "
              f"mis-routed {n_wrong}, abstaining {n_missing}")

        rows = []
        persisted = 0
        t0 = time.time()
        for _, inst in insts.iterrows():
            if (method, inst["instance_id"]) in done:
                continue
            row = sample[sample["sample_id"] == inst["instance_id"]].iloc[0].to_dict()
            kus = [run_unit(routed[q["id"]], row, ctx) for q in canon
                   if routed[q["id"]] is not None]
            backbone = bg.render_ku_backbone(kus) if kus else \
                "NO-COVERAGE: none of the submitted questions could be matched."
            res = refine(row, ctx, backbone)
            rows.append({"method": method, "instance_id": inst["instance_id"],
                         "machine_failure": int(inst["machine_failure"]), "seed": SEED,
                         "latency_s": res["latency_s"],
                         "prompt_tokens": res["prompt_tokens"],
                         "completion_tokens": res["completion_tokens"],
                         "raw_output": res["text"]})
            if len(rows) % 10 == 0:
                print(f"  {cond}: {len(rows)} generated ({time.time()-t0:.0f}s)", flush=True)
                _append_rows(out_path, rows[persisted:])
                persisted = len(rows)
        if len(rows) > persisted:
            _append_rows(out_path, rows[persisted:])
        n = len(pd.read_parquet(out_path))
        print(f"condition {cond}: {n} reports -> {out_path.name}")

    print("\nnext: score with layer1_reports.py + layer2_eval.py/layer3_eval.py "
          "(--judge deepseek --max-tokens 1500), then paraphrase_analysis.py")


if __name__ == "__main__":
    main()
