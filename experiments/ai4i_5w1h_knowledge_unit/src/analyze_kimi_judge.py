"""Compare Kimi-K2.6-judged vs DeepSeek-judged PRIMARY results (B1-B8, n=100).

All 800 canonical reports were generated by GLM-4-Flash; the primary judge was
DeepSeek-V4-Flash (Layers 2-3) and this analysis contrasts it with the fourth
judge Kimi K2.6 (Moonshot), a family disjoint from BOTH the GLM generator and
the DeepSeek primary judge. L1 is programmatic and judge-independent.

Sanity anchor: the DeepSeek side reproduces Table 3 (B1 98.3, B2 83.3,
B3 34.5, B4 36.4, B5 61.3, B6 39.4, B7 36.5, B8 83.9). If DS_Final deviates,
the source assembly below no longer matches composite_final.py.

Outputs: per-system Finals under both judges, Spearman rank agreement,
leniency shift, per-dimension Pearson correlations, paired Wilcoxon B8 vs
every baseline and the B1-vs-B8 Layer-3 comparison (fluency inversion),
plus a B2/B8 layer-level detail block for the paper text.
"""
from __future__ import annotations

import pandas as pd
from scipy import stats

import config as C

ORDER = ["B1", "B2", "B3", "B4", "B5", "B6", "B7", "B8"]
W = {"L1": 0.35, "L2": 0.30, "L3": 0.35}
DIMS = ["faithfulness", "completeness", "coherence", "actionability"]

# Canonical per-system sources (MUST match composite_final.py / Table 3):
# B3-B6 from the main run, B7 from the CoVe-fix v2 run, B1/B2/B8 from the
# rule-engine v3 run. Reading the plain reports_main_glm_n100_* files for
# B1/B2/B7/B8 would compare against superseded reports.
MAIN = "reports_main_glm_n100"
SRC = {s: MAIN for s in ["B3", "B4", "B5", "B6"]}
SRC["B7"] = "reports_main_glm_n100_B7_v2"
for s in ["B1", "B2", "B8"]:
    SRC[s] = "reports_main_glm_n100_B1B2B8_v3"

L2_COLS = ["method", "instance_id", "L2", "consistency", "contradiction"]
L3_COLS = ["method", "instance_id", "L3", "coverage", "ok"] + DIMS


def assemble(col3: str, l2_sources: dict, l3_sources: dict) -> pd.DataFrame:
    """Per-instance L1/L2/L3/Final. l2_sources/l3_sources map each system to
    a file stem (e.g. SRC[m] for the primary judge, or a single kimi stem)."""
    l1 = pd.concat([pd.read_parquet(C.RUNS_DIR / f"{SRC[m]}_l1.parquet")
                    .query("method == @m") for m in ORDER], ignore_index=True)
    l1 = l1[["method", "instance_id", "L1"]]
    l2 = pd.concat([pd.read_parquet(C.RUNS_DIR / f"{l2_sources[m]}_l2.parquet")
                    .query("method == @m") for m in ORDER], ignore_index=True)[L2_COLS]
    l3 = pd.concat([pd.read_parquet(C.RUNS_DIR / f"{l3_sources[m]}_l3.parquet")
                    .query("method == @m") for m in ORDER], ignore_index=True)[L3_COLS]
    d = l1.merge(l2, on=["method", "instance_id"]).merge(l3, on=["method", "instance_id"])
    d["Final"] = W["L1"] * d["L1"] * 100 + W["L2"] * d["L2"] * 100 + W["L3"] * d["L3"] * 20
    return d


kimi_stem = {m: "reports_main_glm_n100_kimi" for m in ORDER}
ds = assemble("l3", SRC, SRC)                       # primary DeepSeek judge
km = assemble("l3", kimi_stem, kimi_stem)           # fourth judge, Kimi K2.6

print("rows: kimi =", len(km), "| deepseek(primary) =", len(ds))
print("judge call failures (ok=False): kimi =", int((~km["ok"]).sum()),
      "| deepseek =", int((~ds["ok"]).sum()))

kmg = km.groupby("method")["Final"].agg(["mean", "std"]).reindex(ORDER)
dsg = ds.groupby("method")["Final"].agg(["mean", "std"]).reindex(ORDER)


def cov_count(c) -> int:
    return sum(c.values()) if isinstance(c, dict) else 0


cov_k = km.groupby("method")["coverage"].apply(lambda s: s.apply(cov_count).mean()).reindex(ORDER)
cov_d = ds.groupby("method")["coverage"].apply(lambda s: s.apply(cov_count).mean()).reindex(ORDER)

tbl = pd.DataFrame({
    "DS_Final": dsg["mean"].round(1), "DS_std": dsg["std"].round(1),
    "Kimi_Final": kmg["mean"].round(1), "Kimi_std": kmg["std"].round(1),
    "Delta": (kmg["mean"] - dsg["mean"]).round(1),
    "DS_Cov": cov_d.round(2), "Kimi_Cov": cov_k.round(2)})
print("\n=== per-system Final, same GLM-4-Flash reports, both judges ===")
print(tbl.to_string())
print("(check: DS_Final must equal Table 3: 98.3 / 83.3 / 34.5 / 36.4 / 61.3 / 39.4 / 36.5 / 83.9)")

rho, p_rho = stats.spearmanr(dsg["mean"].values, kmg["mean"].values)
print(f"\nSpearman rho over system means = {rho:.4f} (p = {p_rho:.2e})")

print("\n=== leniency (Kimi minus primary judge) ===")
print(f"mean L3 shift = {(km['L3'].mean() - ds['L3'].mean()):+.3f} "
      f"(primary {ds['L3'].mean():.3f} -> kimi {km['L3'].mean():.3f})")
print(f"mean Final shift = {(km['Final'].mean() - ds['Final'].mean()):+.1f}")
sd_ratio = (km.groupby("method")["Final"].std() / ds.groupby("method")["Final"].std()).reindex(ORDER)
print("per-system sd ratio (kimi/deepseek):",
      ", ".join(f"{m} {r:.2f}" for m, r in sd_ratio.items()))

print("\n=== per-dimension Pearson correlations, 800 pooled reports ===")
mrg = km.merge(ds, on=["method", "instance_id"], suffixes=("_k", "_d"))
for c in DIMS:
    r, p = stats.pearsonr(mrg[f"{c}_k"], mrg[f"{c}_d"])
    print(f"  {c:14s} r = {r:.2f} (p = {p:.1e})")
rc, _ = stats.pearsonr(mrg["L3_k"], mrg["L3_d"])
print(f"  {'L3':14s} r = {rc:.2f}")


def paired(wide: pd.DataFrame, a: str, b: str, col: str) -> None:
    d = wide[a] - wide[b]
    if (d == 0).all():
        print(f"  {a} vs {b} [{col}]: all differences zero")
        return
    w = stats.wilcoxon(d, zero_method="wilcox", method="auto")
    print(f"  {a} vs {b} [{col}]: mean diff = {d.mean():+.3f}, "
          f"win rate = {(d > 0).mean():.0%}, p = {w.pvalue:.2e}")


print("\n=== paired Wilcoxon under the Kimi judge (per-instance Final) ===")
wide = km.pivot_table(index="instance_id", columns="method", values="Final")
for b in ["B2", "B3", "B4", "B5", "B6", "B7", "B1"]:
    paired(wide, "B8", b, "Final")

print("\n=== B1 vs B8 on Layer 3 (fluency-inversion test) ===")
print(f"  L3 means: B1 = {km[km.method == 'B1']['L3'].mean():.3f}, "
      f"B8 = {km[km.method == 'B8']['L3'].mean():.3f}")
wide3 = km.pivot_table(index="instance_id", columns="method", values="L3")
paired(wide3, "B8", "B1", "L3")

print("\n=== key systems, layer-level detail under the Kimi judge ===")
for meth in ["B1", "B2", "B5", "B8"]:
    sub = km[km["method"] == meth]
    print(f"{meth}: L2={sub['L2'].mean():.3f} "
          f"(cons={sub['consistency'].mean():.3f} contra={sub['contradiction'].mean():.3f}) "
          f"L3={sub['L3'].mean():.2f} Final={sub['Final'].mean():.1f} "
          f"Cov={sub['coverage'].apply(cov_count).mean():.2f}")

out = tbl.copy()
out.insert(0, "System", ORDER)
out_path = C.ANALYSIS_DIR / "kimi_judge_summary.csv"
out.to_csv(out_path, index=False)
print(f"\nsaved: {out_path}")
